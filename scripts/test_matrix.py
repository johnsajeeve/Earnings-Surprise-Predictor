#!/usr/bin/env python3
"""Reversible test matrix: requirement <-> test <-> code (Project-Wide DO-03).

Run from the repository root:
  python3 scripts/test_matrix.py build     write audits/test_matrix.json and audits/test_matrix.md
  python3 scripts/test_matrix.py verify    coverage rules and the check-text lock
  python3 scripts/test_matrix.py accept [--all | ID ...]
                                           record that the tests for these checks were reviewed
                                           against the current check text
  python3 scripts/test_matrix.py trace QUERY
                                           walk the matrix from a check (FR-01-AC1), a test name or
                                           a project file (src/earnings/api/main.py)
  python3 scripts/test_matrix.py results --junit FILE [--coverage FILE] [--out FILE]
                                           merge a pytest run into the matrix

The relationship is stored once, in the markers on the tests (@pytest.mark.req, @pytest.mark.code),
and every view is derived from it, so any direction can be followed and nothing is kept twice.

Three kinds of information, kept apart:
  declared   what the markers say (static, committed in audits/test_matrix.*)
  locked     the text of each check the tests were reviewed against (tests/requirement_checks.lock).
             A reference such as FR-01-AC2 means "the second check of FR-01". If the wording of a
             check changes, or checks are inserted or reordered, its fingerprint changes and
             verify fails until someone reviews the tests and runs accept.
  measured   what a test run showed: pass or fail from the JUnit file, and the project files each
             test really executed from coverage.py (dynamic context = test function). Never
             committed, because it depends on the environment.

Result words follow Deterministic_audit.md Phase D: PASS, FAIL, BLOCKED, NOT TESTED. A PASS says a
test passed. Whether the requirement is satisfied is decided by the audit, not by this table.
Standard library only.
"""

import hashlib
import json
import os
import re
import sys
import xml.etree.ElementTree as ET

import requirement_tests as rt

ROOT = rt.ROOT
LOCK = os.path.join(ROOT, "tests", "requirement_checks.lock")
OUT_JSON = os.path.join(ROOT, "audits", "test_matrix.json")
OUT_MD = os.path.join(ROOT, "audits", "test_matrix.md")
LOCK_HEADER = (
    "# Fingerprint of each acceptance check as it read when its tests were last reviewed.\n"
    "# One line per check: reference, then the first 12 hex digits of sha256 of the check text.\n"
    "# scripts/test_matrix.py verify fails if a check changed, appeared or disappeared.\n"
    "# After reviewing the tests that name a check, run: scripts/test_matrix.py accept ID\n"
)
# Skip reasons that mean the environment or an open decision stops the test, not a missing person
# or measurement.
BLOCKED_KINDS = ("BLOCKED", "NEEDS REPO")


def fingerprint(text):
    """Short fingerprint of a check text. Spacing does not matter, wording does."""
    return hashlib.sha256(" ".join(text.split()).encode("utf-8")).hexdigest()[:12]


# ---------------------------------------------------------------- the static matrix


def build_matrix():
    checks, files = rt.load_index()
    tests = rt.load_tests()
    by_ref = {}
    for t in tests:
        for ref in t["reqs"]:
            by_ref.setdefault(ref, []).append("tests/" + t["key"])
    matrix = {"requirements": {}, "tests": {}, "code": {}}
    for rid, items in checks.items():
        matrix["requirements"][rid] = {
            "document": files[rid],
            "id_level_tests": sorted(by_ref.get(rid, [])),
            "checks": [
                {
                    "ref": ref,
                    "fingerprint": fingerprint(text),
                    "text": " ".join(text.replace("\\", "").split()),
                    "tests": sorted(by_ref.get(ref, [])),
                }
                for ref, text in items
            ],
        }
    for t in tests:
        key = "tests/" + t["key"]
        matrix["tests"][key] = {
            "requirements": sorted(t["reqs"]),
            "code": sorted(t["code"]),
            "kind": t["status"],
        }
        for path in t["code"]:
            entry = matrix["code"].setdefault(path, {"tests": [], "requirements": []})
            entry["tests"].append(key)
            entry["requirements"] = sorted(set(entry["requirements"]) | set(t["reqs"]))
    for entry in matrix["code"].values():
        entry["tests"] = sorted(entry["tests"])
    return matrix


def render_json(matrix):
    return json.dumps(matrix, indent=2, sort_keys=True) + "\n"


def short_test(key):
    return key.split("::", 1)[1]


def render_markdown(matrix):
    out = [
        "# Test Matrix",
        "",
        "Generated by `scripts/test_matrix.py build` from `audits/acceptance_index.md` and the "
        "markers in `tests/`. Do not edit by hand. The same data is in `test_matrix.json`.",
        "",
        "Three views of one relationship. Follow it in any direction with "
        "`python3 scripts/test_matrix.py trace QUERY`.",
        "Kind says what the test is: a real check, an expected failure (the requirement is not met "
        "yet) or a placeholder that is not tested. It does not say a requirement is satisfied.",
        "The fingerprint identifies the wording of the check the tests were reviewed against "
        "(`tests/requirement_checks.lock`).",
        "",
        "## A. Requirement check to tests",
        "",
        "| Check | Fingerprint | Tests (file::name) | Kind |",
        "|---|---|---|---|",
    ]
    tests = matrix["tests"]
    for entry in matrix["requirements"].values():
        for chk in entry["checks"]:
            names = chk["tests"] or ["none"]
            kinds = sorted({tests[k]["kind"] for k in chk["tests"]}) or ["NO TEST"]
            cell = "<br>".join(f"{n.replace('tests/', '')}" for n in names)
            out.append(f"| {chk['ref']} | {chk['fingerprint']} | {cell} | {'; '.join(kinds)} |")
    out += [
        "",
        "## B. Test to requirement checks and code",
        "",
        "| Test | Requirement checks | Code | Kind |",
        "|---|---|---|---|",
    ]
    for key, t in tests.items():
        reqs = ", ".join(t["requirements"])
        code = ", ".join(t["code"]) or "none yet"
        out.append(f"| {key.replace('tests/', '')} | {reqs} | {code} | {t['kind']} |")
    out += [
        "",
        "## C. Code to tests and requirements",
        "",
        "| Project file | Tests | Requirement checks |",
        "|---|---|---|",
    ]
    for path, entry in sorted(matrix["code"].items()):
        names = "<br>".join(short_test(k) for k in entry["tests"])
        out.append(f"| {path} | {names} | {', '.join(entry['requirements'])} |")
    out.append("")
    return "\n".join(out)


def build():
    matrix = build_matrix()
    with open(OUT_JSON, "w", encoding="utf-8") as fh:
        fh.write(render_json(matrix))
    with open(OUT_MD, "w", encoding="utf-8") as fh:
        fh.write(render_markdown(matrix))
    print(
        f"wrote audits/test_matrix.json and audits/test_matrix.md: "
        f"{len(matrix['requirements'])} requirements, {len(matrix['tests'])} tests, "
        f"{len(matrix['code'])} code files"
    )
    return 0


# ---------------------------------------------------------------- the lock


def current_fingerprints():
    checks, _ = rt.load_index()
    return {ref: fingerprint(text) for items in checks.values() for ref, text in items}


def read_lock(path=LOCK):
    out = {}
    if os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                if line.strip() and not line.startswith("#"):
                    ref, fp = line.split()
                    out[ref] = fp
    return out


def lock_problems(current, locked):
    """Differences between the check texts now and the texts the tests were reviewed against."""
    problems = []
    for ref in sorted(set(current) - set(locked), key=rt_sort):
        problems.append(f"{ref}: new check, review its tests then run accept")
    for ref in sorted(set(locked) - set(current), key=rt_sort):
        problems.append(f"{ref}: check removed or renumbered, review its tests then run accept")
    for ref in sorted(set(current) & set(locked), key=rt_sort):
        if current[ref] != locked[ref]:
            problems.append(f"{ref}: wording changed since its tests were reviewed, run accept")
    return problems


def rt_sort(ref):
    m = re.match(r"^([A-Z]+)-?(\d+)-AC(\d+)$", ref)
    return (m.group(1), int(m.group(2)), int(m.group(3))) if m else (ref, 0, 0)


def verify():
    problems = lock_problems(current_fingerprints(), read_lock())
    status = rt.check()
    if problems:
        print("FAIL (check text lock)")
        for p in problems:
            print(" -", p)
        return 1
    print("OK: every check matches the text its tests were reviewed against")
    return status


def accept(args):
    current = current_fingerprints()
    locked = read_lock()
    if args == ["--all"]:
        chosen = set(current) | set(locked)
    else:
        chosen = {ref for ref in set(current) | set(locked) if ref.split("-AC")[0] in args}
        if not chosen:
            print("no check matches", args)
            return 2
    for ref in chosen:
        if ref in current:
            locked[ref] = current[ref]
        else:
            locked.pop(ref, None)
    with open(LOCK, "w", encoding="utf-8") as fh:
        fh.write(LOCK_HEADER)
        for ref in sorted(locked, key=rt_sort):
            fh.write(f"{ref} {locked[ref]}\n")
    print(f"tests/requirement_checks.lock: {len(locked)} checks recorded")
    return 0


# ---------------------------------------------------------------- walking the matrix


def trace(query):
    with open(OUT_JSON, encoding="utf-8") as fh:
        matrix = json.load(fh)
    found = False
    rid = query.split("-AC")[0]
    if rid in matrix["requirements"]:
        for chk in matrix["requirements"][rid]["checks"]:
            if "-AC" in query and chk["ref"] != query:
                continue
            found = True
            print(f"{chk['ref']}  [{chk['fingerprint']}]  {chk['text']}")
            for key in chk["tests"] or ["(no test)"]:
                t = matrix["tests"].get(key, {})
                print(f"    test {key}  [{t.get('kind', '')}]")
                for path in t.get("code", []):
                    print(f"        code {path}")
        for key in matrix["requirements"][rid]["id_level_tests"]:
            print(f"    test (whole requirement) {key}")
    for key, t in matrix["tests"].items():
        if query in key:
            found = True
            print(f"{key}  [{t['kind']}]")
            print("    checks:", ", ".join(t["requirements"]))
            print("    code:", ", ".join(t["code"]) or "none yet")
    if query in matrix["code"]:
        found = True
        entry = matrix["code"][query]
        print(f"{query}")
        print("    requirement checks:", ", ".join(entry["requirements"]))
        for key in entry["tests"]:
            print(f"    test {key}")
    if not found:
        print("nothing in the matrix matches", query)
        return 1
    return 0


# ---------------------------------------------------------------- measured results


def parse_junit(xml_text):
    """Map test key (tests/file.py::name) to a list of outcomes, one per parametrized case."""
    outcomes = {}
    for case in ET.fromstring(xml_text).iter("testcase"):
        module = case.get("classname", "").split(".")[-1]
        key = f"tests/{module}.py::{case.get('name', '').split('[')[0]}"
        child = next(iter(case), None)
        if child is None:
            outcome = "PASS"
        elif child.tag in ("failure", "error"):
            outcome = "FAIL"
        else:  # skipped: a placeholder, an environment skip, or an expected failure
            message = child.get("message", "")
            if child.get("type") == "pytest.xfail":
                outcome = "FAIL (known, requirement not met yet)"
            elif any(kind in message for kind in BLOCKED_KINDS):
                outcome = "BLOCKED"
            else:
                outcome = "NOT TESTED"
        outcomes.setdefault(key, []).append(outcome)
    return outcomes


ORDER = ("FAIL", "FAIL (known, requirement not met yet)", "PASS", "BLOCKED")


def strongest(results_list):
    """The first of FAIL, known FAIL, PASS, BLOCKED present, else NOT TESTED.

    Used for a test (over its parametrized cases) and for a check (over the tests naming it).
    """
    for word in ORDER:
        if word in results_list:
            return word
    return "NOT TESTED"


def parse_coverage(data):
    """Map test key to the project files it executed, from coverage.py JSON with contexts."""
    seen = {}
    for path, info in data.get("files", {}).items():
        norm = path.replace("\\", "/")
        if "src/" in norm:
            norm = norm[norm.index("src/") :]
        for contexts in info.get("contexts", {}).values():
            for ctx in contexts:
                if not ctx:
                    continue
                parts = ctx.split(".")
                key = f"tests/{parts[0]}.py::{parts[-1]}"
                seen.setdefault(key, set()).add(norm)
    return {k: sorted(v) for k, v in seen.items()}


def results(junit_path, coverage_path, out_path):
    matrix = build_matrix()
    with open(junit_path, encoding="utf-8") as fh:
        outcomes = parse_junit(fh.read())
    measured = {}
    if coverage_path:
        with open(coverage_path, encoding="utf-8") as fh:
            measured = parse_coverage(json.load(fh))
    per_test = {key: strongest(outcomes.get(key, [])) for key in matrix["tests"]}
    lines = [
        "# Test matrix with measured results",
        "",
        "Merged from a pytest JUnit file"
        + (" and a coverage.py JSON file" if coverage_path else "")
        + ". Not committed: it depends on the environment. A PASS means a test passed. "
        "It does not say the requirement is satisfied.",
        "",
    ]
    tally = {}
    rows = []
    for entry in matrix["requirements"].values():
        for chk in entry["checks"]:
            res = strongest([per_test[k] for k in chk["tests"]])
            tally[res] = tally.get(res, 0) + 1
            names = "<br>".join(short_test(k) for k in chk["tests"]) or "none"
            rows.append(f"| {chk['ref']} | {res} | {names} |")
    lines += ["## Summary of acceptance checks", "", "| Result | Checks |", "|---|---|"]
    for res in sorted(tally):
        lines.append(f"| {res} | {tally[res]} |")
    lines += ["", "## Per check", "", "| Check | Result | Tests |", "|---|---|---|", *rows, ""]
    if coverage_path:
        lines += [
            "## Code each test executed (measured) against the code its markers declare",
            "",
            "Tests that only read files (documents, CI, source scans) execute no project code, so "
            "a declared file shown as not observed is expected for them. Code that runs when a "
            "module is imported (class bodies, module level lines) belongs to no test.",
            "",
            "| Test | Executed, not declared | Declared in src/, not observed |",
            "|---|---|---|",
        ]
        for key, t in matrix["tests"].items():
            if per_test[key] not in ("PASS", "FAIL"):
                continue
            seen = set(measured.get(key, []))
            declared = {p for p in t["code"] if p.startswith("src/")}
            extra, missing = sorted(seen - set(t["code"])), sorted(declared - seen)
            if extra or missing:
                lines.append(f"| {short_test(key)} | {', '.join(extra)} | {', '.join(missing)} |")
        lines.append("")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(
        f"wrote {os.path.relpath(out_path, ROOT)}: "
        + ", ".join(f"{k} {v}" for k, v in sorted(tally.items()))
    )
    return 0


def option(argv, name):
    return argv[argv.index(name) + 1] if name in argv else None


def main(argv):
    command = argv[1] if len(argv) > 1 else ""
    if command == "build":
        return build()
    if command == "verify":
        return verify()
    if command == "accept" and len(argv) > 2:
        return accept(argv[2:])
    if command == "trace" and len(argv) == 3:
        return trace(argv[2])
    if command == "results" and option(argv, "--junit"):
        out = option(argv, "--out") or os.path.join(ROOT, "test-results", "test_matrix_results.md")
        return results(option(argv, "--junit"), option(argv, "--coverage"), out)
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
